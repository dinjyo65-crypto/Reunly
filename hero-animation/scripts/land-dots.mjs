// Generates ../globe-land.js: a dot grid over the world's land, for the app's
// in-plan journey globe. The app has no build step and a script-src 'self'
// CSP, so instead of shipping d3 + topojson it gets pre-sampled points it can
// project with a few lines of maths. Run: node scripts/land-dots.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const topo = JSON.parse(
  readFileSync(new URL("../node_modules/world-atlas/land-110m.json", import.meta.url)),
);
const land = feature(topo, topo.objects.land);

const STEP = 2.6; // degrees of latitude between rows
const dots = [];
for (let lat = -58; lat <= 78; lat += STEP) {
  // Keep spacing roughly even on the sphere: fewer dots per row near the poles.
  const lonStep = STEP / Math.max(0.25, Math.cos((lat * Math.PI) / 180));
  for (let lon = -180; lon < 180; lon += lonStep) {
    if (geoContains(land, [lon, lat])) dots.push([+lon.toFixed(1), +lat.toFixed(1)]);
  }
}

const out = `// Generated by hero-animation/scripts/land-dots.mjs — do not edit by hand.
// [lon, lat] points on land (Natural Earth 110m via world-atlas), ~${STEP}° grid.
window.ReunlyLand = ${JSON.stringify(dots)};
`;
writeFileSync(new URL("../../globe-land.js", import.meta.url), out);
console.log(`${dots.length} dots, ${out.length} bytes`);
